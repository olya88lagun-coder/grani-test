// Тексты формы кода закрытого пилота. Сервер отвечает только «код не подошёл», без подсказок, какая часть кода верна
export function pilotCodeFailure(status: number, code: string): string {
  if (status === 0 || status >= 500) return "Не получилось связаться с сервером. Повторите попытку.";
  if (status === 401) return "Нужно войти заново. После входа вернём вас сюда.";
  if (status === 429) return "Слишком много попыток. Подождите минуту и повторите.";
  if (code === "invalid_code") return "Код не подошёл. Проверьте его и введите ещё раз.";
  if (code === "limit_reached") return "Все места в пилоте заняты. Попробуйте позже.";
  return "Не получилось выполнить действие. Проверьте данные и повторите.";
}

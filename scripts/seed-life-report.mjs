const sql = postgres(databaseUrl, { max: 1 });
try {
  await sql`delete from reports where result_id = ${resultId} and kind = 'life'`;
  if (flag !== "--remove") {
    await sql`insert into reports (result_id, kind, sections, source) values (${resultId}, 'life', ${sql.json({ version: 1, situations: CARDS })}, 'ai')`;
    console.log(`Отчёт life добавлен для ${resultId}`);
  } else {
    console.log(`Отчёт life удалён для ${resultId}`);
  }
} finally {
  await sql.end();
}
